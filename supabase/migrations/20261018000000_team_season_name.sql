-- Club names by season. hokej.cz match pages give a club's name of that season only from about
-- 2003, and even then not everywhere (generic "Pardubice", "Č. Budějovice"); before that they show
-- the current name (Třinec as "HC Oceláři Třinec" in 1995). The names below follow the clubs'
-- name histories on Czech Wikipedia (a rename in year Y applies from season Y/Y+1), taking
-- hokej.cz's name where Wikipedia's list is incomplete (Kometa since 2009, Dukla Jihlava) or
-- differs only in capitals (HC VERVA Litvínov). The current season reads team.name.
create table if not exists team_season_name (
  team_id text not null references team(id),
  league_id text not null,
  season int not null,
  name text not null,
  source text not null,
  primary key (team_id, league_id, season)
);
