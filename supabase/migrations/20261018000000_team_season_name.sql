create or replace function season_team_name(p_team text, p_season int) returns text
language sql stable as $$
  select n.name from team_season_name n where n.team_id = p_team and n.season = p_season
  order by n.league_id = 'cz-elh' desc limit 1
$$;

-- Crests before 2014/15: hokej.cz shows each club's one older crest for every earlier season, so a
-- crest is kept only for seasons in which the club bore the name it had when it last wore that
-- crest (Třinec's "Oceláři" dragon not for 1995-1998, when the club was HC Železárny Třinec).
-- Elsewhere the crest is unknown and a neutral badge is shown rather than an anachronism.
alter table team_season_logo alter column logo_url drop not null;

update team_season_logo l set logo_url = null
from (
  select team_id, league_id, logo_url, max(season) as last_season
  from team_season_logo where logo_url is not null group by 1, 2, 3
) e
where l.team_id = e.team_id and l.league_id = e.league_id and l.logo_url = e.logo_url
  and l.season < 2014
  and season_team_name(l.team_id, l.season) is distinct from season_team_name(e.team_id, e.last_season);

-- A past season without a known crest shows none; only the current season falls back to the
-- club's current crest.
create or replace function season_logo(p_team text, p_season int) returns text
language sql stable as $$
  select case
    when exists (select 1 from team_season_logo l where l.team_id = p_team and l.season = p_season)
      then (select l.logo_url from team_season_logo l where l.team_id = p_team and l.season = p_season
            order by l.league_id = 'cz-elh' desc limit 1)
    when p_season >= (select coalesce(max(season), 0) from game where league_id = 'cz-elh') - 0
      then (select t.logo_url from team t where t.id = p_team)
    else null
  end
$$;
