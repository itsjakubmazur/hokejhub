// Embeds supabase/migrations/*.sql into a TS module so the /api/admin/migrate route can run
// them on Vercel (the SQL files live outside the Next.js project root).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "../../../supabase/migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((name) => ({ name, sql: readFileSync(join(dir, name), "utf8") }));
const out = `// Generated by scripts/embed-migrations.mjs — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(join(import.meta.dirname, "../lib/server/migrations.generated.ts"), out);
console.log(`embedded ${files.length} migrations`);
